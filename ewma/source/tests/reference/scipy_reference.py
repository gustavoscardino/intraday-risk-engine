def es_unit(nu, c):
    """ES of the unit-variance t (or Normal for nu = inf) by numerical integration."""
    if math.isinf(nu):
        q = stats.norm.ppf(c)
        val, _ = integrate.quad(lambda z: z * stats.norm.pdf(z), -math.inf, -q, epsabs=1e-14, epsrel=1e-13)
        return q, -val / (1 - c)
    k = math.sqrt((nu - 2) / nu)
    q = -k * stats.t.ppf(1 - c, nu)
    # Z = k T: E[Z; Z < -q] = k E[T; T < -q / k]
    val, _ = integrate.quad(lambda t: t * stats.t.pdf(t, nu), -math.inf, -q / k, epsabs=1e-14, epsrel=1e-13)
    return q, -k * val / (1 - c)


