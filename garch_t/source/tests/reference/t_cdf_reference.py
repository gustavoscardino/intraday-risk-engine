"""Reference values of the Student-t CDF for tests/test_main.cpp (t_cdf_reference.inc).

F(x; nu) = I_z(nu/2, 1/2) / 2 for x < 0 (z = nu / (nu + x^2)), from mpmath's regularized
incomplete beta at 40+ significant digits; for z > 1/2 through 1 - I_w(1/2, nu/2) with enough
working digits for the cancellation. Covers the continued-fraction (nu < 30, far tails) and the
large-nu expansion paths of math::t_cdf, deep tails included.

    python t_cdf_reference.py > t_cdf_reference.inc
"""
import mpmath as mp

NUS = [0.5, 2.05, 7, 15, 29.9, 30, 45, 128.5, 300, 5000, 1e5, 1e6]
XS = [-1e6, -200, -38, -12, -2.3263, -0.1, 1.2, 9]


def cdf(nu, x):
    mp.mp.dps = 40
    nu, x = mp.mpf(nu), mp.mpf(x)
    x2 = x * x
    z = nu / (nu + x2)
    if z <= 0.5:
        tail = mp.betainc(nu / 2, mp.mpf(1) / 2, 0, z, regularized=True) / 2
    else:
        guess = mp.erfc(abs(x) / mp.sqrt(2)) / 2 + mp.mpf(10) ** -320
        with mp.workdps(max(40, int(-mp.log10(guess)) + 40)):
            w = x2 / (nu + x2)
            tail = (1 - mp.betainc(mp.mpf(1) / 2, nu / 2, 0, w, regularized=True)) / 2
    return tail if x < 0 else 1 - tail


print("        // generated by tests/reference/t_cdf_reference.py (mpmath, 40+ digits)")
for nu in NUS:
    for x in XS:
        if nu > 1000 and abs(x) > 20:  # below double range at large nu
            continue
        F = cdf(nu, x)
        if F < mp.mpf("1e-300"):
            continue
        print("        {%r, %r, %s}," % (nu, x, mp.nstr(F, 20, min_fixed=1, max_fixed=0)))
